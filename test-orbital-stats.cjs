const fs=require('node:fs');
const assert=require('node:assert/strict');
const source=fs.readFileSync(process.cwd()+'/dist/orbital-lift.js','utf8');
const body=source.slice(source.indexOf(' function scaledStats'),source.indexOf(' const statNumber'));
const calculate=new Function(body+';return scaledStats;')();
const weaponBody=source.slice(source.indexOf(' function weaponStats'),source.indexOf(' let equipment='));
const weaponCalculate=new Function(weaponBody+';return weaponStats;')();
const equipment=JSON.parse(fs.readFileSync(process.cwd()+'/dist/data/orbital-weapons.json','utf8'));
const bow=weaponCalculate(equipment.items[9091144],181,equipment.scales);
const shuran=weaponCalculate(equipment.items[9093894],181,equipment.scales);
assert.equal(bow.scale,410.5);
assert(Math.abs(bow.attack/shuran.attack-14.6074)<0.001);
assert.equal(bow.defense,null);
assert.equal(weaponCalculate(equipment.items[9094254],181,equipment.scales).attack,null);
assert.equal(weaponCalculate(equipment.items[9091144],999,equipment.scales),null);
assert.equal(weaponCalculate({Damage:2,StatGrowthRate:1,LevelScale:false},0,{}).attack,2);
for(const item of Object.values(equipment.items))assert(weaponCalculate(item,181,equipment.scales));
assert(source.includes('${weaponMarkup(s,f)}'));
console.log('Weapon checks passed; level 182 bow ATK:',bow.attack,'Shuran ATK:',shuran.attack);
const formatBody=source.slice(source.indexOf(' const statNumber'),source.indexOf(' function statsMarkup'));
const format=new Function(formatBody+';return statNumber;')();
assert.equal(format(10205951),'10.205.951');
assert.equal(format(1595.12),'1.595,12');
assert.equal(format(540.41),'540,41');
assert.equal(format(2.8),'2,8');
const spec={Hp:2808.2782,Atk:31.625,Def:15,StatGrowthRate:1.02};
const floor={StandardLevel:181};
const normal=calculate(spec,floor,[]);
const elite=calculate(spec,floor,[{OptionId:200022,Level:1}]);
assert.equal(normal.level,182);
assert.equal(elite.hp,10205951);
assert.equal(elite.elite,'verified');
assert.equal(elite.atkMultiplier,1.4);
assert.equal(elite.atk,Math.fround(normal.atk*Math.fround(1.4)));
for(const id of [200001,200021,200010]){
 const result=calculate(spec,floor,[{OptionId:id,Level:1}]);
 assert.equal(result.elite,id===200010?'verified':'estimated');
 assert.equal(result.hpMultiplier,id===200010?4.2:2.8);
 assert.equal(result.hp,Math.trunc(Math.fround(Math.fround(Math.fround(spec.Hp)*Math.fround(Math.fround(Math.fround(1.02)**2)**181))*Math.fround(result.hpMultiplier))));
 assert.equal(result.atkMultiplier,id===200010?1.6:1.4);
 assert.equal(result.atk,Math.fround(normal.atk*Math.fround(result.atkMultiplier)));
 assert.equal(result.combatElite,'estimated');
 assert.equal(result.mortarParametersAssumed,id===200001);
 assert.equal(result.def,normal.def);
}
const unknown=calculate(spec,floor,[{OptionId:999999,Level:1}]);
assert.equal(unknown.elite,'unverified');
assert.equal(unknown.hp,normal.hp);
assert.equal(calculate(spec,{StandardLevel:0},[]).hp,2808);
assert.equal(calculate({...spec,Hp:undefined},floor,[]),null);
assert(source.includes('statsMarkup(s,f,m)'));
assert(source.includes('scaledStats:scaledStats('));
assert(source.includes("location.pathname+'?floor='"));
console.log('PASS: level mapping, float32 HP, verified/unknown elites, base ATK/DEF, missing data, render and export integration.');
